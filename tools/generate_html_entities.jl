#!/usr/bin/env julia
# generate_html_entities.jl — writes `src/html_entities_table.jl`, the table of HTML named
# character references that `decode_named_entities` reads.
#
# Usage:
#     julia tools/generate_html_entities.jl                  # download entities.json
#     julia tools/generate_html_entities.jl entities.json    # read a local copy
#
# The HTML standard declares its list of names static, so the table changes only if this
# script does. Run again on the same list, it writes the same file byte for byte. JSON.jl
# is installed in a temporary environment: FastKML itself does not depend on it.

using Pkg
Pkg.activate(; temp = true, io = devnull)
Pkg.add("JSON"; io = devnull)

using Downloads, JSON, SHA

