# Escape every code point, ASCII included: the file stays ASCII apart from the notice, and
# no value can open an interpolation or end its literal.
escape_code_points(cps) =
    join(cp <= 0xffff ? "\\u" * string(cp; base = 16, pad = 4) :
                        "\\U" * string(cp; base = 16, pad = 8) for cp in cps)

function main(args)
    bytes = isempty(args) ? take!(Downloads.download(ENTITY_URL, IOBuffer())) : read(args[1])
    digest = bytes2hex(sha256(bytes))
    json = JSON.parse(String(copy(bytes)))

    entries = Pair{String,Vector{Int}}[]
    for (key, val) in json
        # Historical forms are written without their semicolon (`&amp`, `&para`);
        # `decode_named_entities` only matches a name followed by one.
        endswith(key, ";") || continue
        name = String(chop(key; head = 1, tail = 1))
        all(c -> isascii(c) && (isletter(c) || isdigit(c)), name) ||
            error("unexpected entity name $key")
        cps = Int.(val["codepoints"])
        String(Char.(cps)) == val["characters"] ||
            error("code points and characters differ for $key")
        push!(entries, name => cps)
    end
    sort!(entries; by = first)
    nhistorical = length(json) - length(entries)

    open(OUTPUT, "w") do io
        println(io, "# This file is generated by tools/generate_html_entities.jl; do not edit it by hand.")
        println(io, "#")
        println(io, "# The named character references of the HTML standard, each written with its semicolon:")
        println(io, "# $(length(entries)) of the $(length(json)) keys of $ENTITY_URL")
        println(io, "# (SHA-256 $digest).")
        println(io, "# The $nhistorical other keys are historical forms without a semicolon, which")
        println(io, "# `decode_named_entities` never matches. The standard declares the list static.")
        println(io, "# Each value is written as code-point escapes.")
        println(io, "#")
        for line in eachsplit(NOTICE, '\n')
            println(io, isempty(line) ? "#" : "# " * line)
        end
        println(io)
        println(io, "const NAMED_HTML_ENTITIES = Dict{String,String}(")
        for (name, cps) in entries
            println(io, "    \"", name, "\" => \"", escape_code_points(cps), "\",")
        end
        println(io, ")")
    end
    println("wrote ", length(entries), " names to ", OUTPUT)
end

main(ARGS)
